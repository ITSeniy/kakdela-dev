import type { SVGProps } from 'react'

export interface IconProps extends SVGProps<SVGSVGElement> {
  size?: number
}

function makeIcon(children: React.ReactNode, fill: 'none' | 'currentColor' = 'none') {
  return function IconGlyph({ size = 15, ...rest }: IconProps) {
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill={fill}
        stroke={fill === 'none' ? 'currentColor' : undefined}
        strokeWidth={fill === 'none' ? 2 : undefined}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        {...rest}
      >
        {children}
      </svg>
    )
  }
}

